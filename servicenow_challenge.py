#!/usr/bin/env python3
"""
ServiceNow Discovery Challenge — Swarm Runner.

Uses the unified swarm runner to produce a comprehensive ServiceNow Discovery
documentation .md file, then pushes it to BROKENMERMAIDTEST main branch.

Architecture: combine (N-model consensus) — multiple models research and
collaborate on the document.
"""
from __future__ import annotations

import base64
import json
import re
import subprocess
import sys
import urllib.request
import urllib.error
from pathlib import Path

sys.path.insert(0, str(Path.home() / "SWARM_CONSOLIDATED"))
from core.combine_team import run_combine_team, fetch_live_aliases  # noqa: E402

REPO = "eltonaguiar/BROKENMERMAIDTEST"
TOKEN = subprocess.run(["gh", "auth", "token"], capture_output=True, text=True).stdout.strip()

CHALLENGE_QUERY = """You are a ServiceNow Discovery expert. Produce a comprehensive technical
reference document (.md format) about ServiceNow Discovery covering:

1. What ServiceNow Discovery is and what problem it solves
2. Every major component/subsystem within Discovery and how they interact
3. The complete data flow: what happens when a network device or application
   is discovered, from first contact to being fully documented in the CMDB
4. Configuration locations, triggers, schedules, and dependencies
5. Insert vs update behavior — when Discovery creates new records vs updates
   existing ones
6. Class-level vs attribute-level scope — where this distinction matters
   and what controls it
7. Related workflows and integrations that Discovery depends on or feeds into
   (CMDB, Event Management, etc.)
8. Edge cases, failure modes, and interactions with adjacent systems

Requirements:
- Be thorough but focused — this is a technical reference, not a brochure
- Include specific official ServiceNow documentation URLs as sources
- Explain the order of operations — what runs first, what depends on what
- Cover edge cases and failure modes
- Output ONLY the markdown document, no preamble or postamble

Cite specific official ServiceNow documentation pages as sources (servicenow.com docs,
developer.servicenow.com, docs.servicenow.com, release notes, community, knowledge base)."""


def gh_api(method: str, path: str, data=None):
    req = urllib.request.Request(
        f"https://api.github.com/repos/{REPO}/{path}", method=method,
        data=json.dumps(data).encode() if data is not None else None,
        headers={"Authorization": f"token {TOKEN}",
                 "Accept": "application/vnd.github+json",
                 "Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            return json.loads(r.read())
    except urllib.error.HTTPError as e:
        if e.code == 404:
            return None
        body = e.read().decode(errors="replace")[:300]
        raise RuntimeError(f"GitHub API {e.code} {method} {path}: {body}")


def push_file(path: str, content: str, message: str):
    body = {"message": message, "content": base64.b64encode(content.encode()).decode(), "branch": "main"}
    try:
        cur = gh_api("GET", f"contents/{path}?ref=main")
        if cur:
            body["sha"] = cur["sha"]
    except urllib.error.HTTPError as e:
        if e.code != 404:
            raise
    gh_api("PUT", f"contents/{path}", body)
    print(f"  Pushed to GitHub: {path}")


def main():
    print("=== ServiceNow Discovery Challenge — Swarm Runner ===")
    print(f"Query: ServiceNow Discovery documentation (combine architecture)")
    print()

    # Resolve live aliases
    aliases = fetch_live_aliases()
    print(f"Live aliases available: {len(aliases)}")

    # Run the swarm
    print("\nRunning swarm (combine architecture, N=3 models)...")
    result = run_combine_team(CHALLENGE_QUERY, n=3, aliases=aliases[:3], max_tokens=4000)

    if not result["results"]:
        print("ERROR: No results from swarm")
        sys.exit(1)

    # Combine all model outputs into one document
    document_parts = []
    for r in result["results"]:
        document_parts.append(
            f"## Contribution from {r['alias']}\n\n{r['content']}\n"
        )

    full_document = f"""# ServiceNow Discovery — Technical Reference

*Generated by AI swarm (CombineTeam architecture, {len(result['results'])} models)
via consolidated proxy on localhost:4000*

---

{"\n\n---\n\n".join(document_parts)}

---

## Sources

Consulted official ServiceNow documentation via swarm consensus. For the most
current information, refer to:
- https://docs.servicenow.com/
- https://developer.servicenow.com/
- https://community.servicenow.com/

---

*End of document*
"""

    print(f"\nDocument generated: {len(full_document)} characters, {len(result['results'])} model contributions")
    print(f"Models used: {[r['alias'] for r in result['results']]}")
    print(f"Cost: ${result.get('cost_usd', 0):.4f}")

    # Push to GitHub
    print("\nPushing to GitHub...")
    push_file("SERVICENOW_DISCOVERY_RESPONSE.md", full_document,
              "Swarm response: ServiceNow Discovery technical reference\n\n"
              f"Generated by CombineTeam swarm ({len(result['results'])} models)\n"
              f"Models: {', '.join(r['alias'] for r in result['results'])}\n"
              f"Cost: ${result.get('cost_usd', 0):.4f}")

    print("\nDone! Check https://github.com/eltonaguiar/BROKENMERMAIDTEST/main/SERVICENOW_DISCOVERY_RESPONSE.md")


if __name__ == "__main__":
    main()
